def _find_resource_dir(clang_tidy_exe: str) -> Optional[str]:
    """Find the resource directory relative to clang-tidy executable without spawning subprocess."""
    try:
        exe_path = Path(clang_tidy_exe).resolve()
        for lib_dir_name in ("lib", "lib64"):
            lib_clang = exe_path.parent.parent / lib_dir_name / "clang"
            if lib_clang.is_dir():
                versions = [p for p in lib_clang.iterdir() if p.is_dir()]
                if versions:
                    return str(sorted(versions)[-1])
    except Exception:
        pass
    return None


_CACHED_RESOURCE_DIR: Optional[str] = None


def _extract_resource_dir(compiler_flags: List[str], clang_tidy_exe: str = "") -> str:
    """Gets the actual resource directory, preferring direct directory lookup and caching."""
    global _CACHED_RESOURCE_DIR
    if _CACHED_RESOURCE_DIR:
        return _CACHED_RESOURCE_DIR

    if clang_tidy_exe:
        found = _find_resource_dir(clang_tidy_exe)
        if found:
            _CACHED_RESOURCE_DIR = found
            return found

    res = subprocess.check_output(
        compiler_flags + ["-print-resource-dir"],
        text=True,
    ).strip()
    _CACHED_RESOURCE_DIR = res
    return res


def _filter_duplicate_resource_dir_flags(raw_flags: List[str]) -> List[str]:
    """Filters out explicit toolchain Clang resource directory include paths from compiler flags.

    When running clang-tidy, `-extra-arg=-resource-dir={resource_dir}` is passed so clang-tidy
    knows its own builtin header location. If the toolchain also generates `-isystem` or `-I`
    flags pointing to the toolchain's `lib/clang/<version>/include` directory, Clang's header
    search path ends up with duplicate resource directories (one relative, one absolute).

    This causes Clang builtin headers using `#include_next` (such as `stdint.h`) to resolve to
    the second Clang resource directory rather than chaining to the SDK/system C library headers,
    breaking fundamental type definitions like `uint8_t`, `uint32_t`, etc.

    Args:
        raw_flags: List of raw compiler flags extracted from the flags file.

    Returns:
        List of sanitized flags with duplicate Clang resource directory includes removed.
    """
    filtered_flags: List[str] = []
    i = 0
    while i < len(raw_flags):
        flag = raw_flags[i]
        # Check for two-part include flag, e.g.: -isystem <path>/lib/clang/<version>/include
        if (
            flag in ("-isystem", "-I")
            and i + 1 < len(raw_flags)
            and "/lib/clang/" in raw_flags[i + 1]
            and raw_flags[i + 1].endswith("/include")
        ):
            i += 2
            continue
        # Check for joined include flag, e.g.: -isystem<path>/lib/clang/<version>/include
        if (
            (flag.startswith("-isystem") or flag.startswith("-I"))
            and "/lib/clang/" in flag
            and flag.endswith("/include")
        ):
            i += 1
            continue
        filtered_flags.append(flag)
        i += 1
    return filtered_flags


def _handle_generate(args: argparse.Namespace) -> None:
    """
    Runs clang-tidy on a single source file

    Args:
        args: Parsed arguments containing warnings_file, input_file, and exec_root.
        compiler_flags: The raw list of flags meant for the compiler (e.g. ['-I.', '-O2']).
    """
    # 1. Clean up compiler flags
    # If the flags start with '--', it's a separator passed by Bazel to protect
    # the flags from our argparse. We must remove it before constructing the command.
    compiler_flags = []
    if args.flags_file:
        with open(args.flags_file, "r") as f:
            raw_flags = [line.strip() for line in f if line.strip()]
        compiler_flags = _filter_duplicate_resource_dir_flags(raw_flags)

    compiler_flags = compiler_flags + ["-c", args.source_file]
    logging.debug("Cleaned compiler flags: %s", compiler_flags)
    # Tidy will incorrectly resolve the resource_directory outside
    # of the sandbox which would result clang not finding standard headers,
    # we have to invoke clang with the complete flag configuration to get it.
    resource_dir = _extract_resource_dir(compiler_flags, args.clang_tidy_exe)
    logging.debug("Extracted resource dir: %s", resource_dir)

    tidy_cmd = [
        args.clang_tidy_exe,
        f"--config-file={args.config_file}",
        f"--export-fixes={args.fixes_file}",
        f"-extra-arg=-resource-dir={resource_dir}",
    ]
    if getattr(args, "line_filter", ""):
        tidy_cmd.append(f"--line-filter={args.line_filter}")
    tidy_cmd += [
        args.source_file,
        "--",
    ] + compiler_flags

    logging.debug("Running clang-tidy command: %s", " ".join(tidy_cmd))
    res = subprocess.run(
        tidy_cmd,
        stdout=subprocess.PIPE,
        stderr=subprocess.DEVNULL,  # suppress noise.
        text=True,
        check=False,
    )

    if res.stdout:
        sys.stdout.write(res.stdout)

    # Make sure an export with fixes exist.
    if not Path(args.fixes_file).exists():
        with open(args.fixes_file, "a") as fexp:
            fexp.write("\n")

    rewriter = ReportRewriter(
        Path.cwd(), load_config_from_file(args.config_file), args.rewrite_rules
    )
    rewriter.rewrite_fixes(args.fixes_file, args.fixes_file)


def _parse_fixes_from_yaml(yaml_files: List[str]) -> Dict[str, List[Dict[str, Any]]]:
    """Parses a list of YAML files to extract replacement information.

    Args:
        yaml_files: A list of paths to YAML files from clang-tidy.

    Returns:
        A dictionary mapping file paths to a list of fix dictionaries.
        Each fix dictionary contains 'offset', 'length', and 'text'.
    """
    fixes_map = {}
    for file_path in yaml_files:
        if not Path(file_path).exists():
            print(f"Warning: Fixes file not found: {file_path}", file=sys.stderr)
            continue
        with open(file_path, "r") as f:
            data = yaml.load(f, Loader=Loader)

        if not "Diagnostics" in data:
            return fixes_map

        diagnostics = data["Diagnostics"]
        for diagnostic in diagnostics:
            if not (
                "DiagnosticMessage" in diagnostic and "DiagnosticName" in diagnostic
            ):
                continue

            name = diagnostic["DiagnosticName"]
            if not name in SIMPLE_FIX_DIAGNOSTIC:
                logging.info("Cannot apply %s, skipping", name)
                continue

            message = diagnostic["DiagnosticMessage"]
            if not "Replacements" in message:
                continue

            replacements = message["Replacements"]
            REQUIRED_FIELDS = Replacement._fields
            for replacement in replacements:
                filepath = replacement["FilePath"]
                if filepath not in fixes_map:
                    fixes_map[filepath] = set()
                filtered_replacement = {
                    k: v for k, v in replacement.items() if k in REQUIRED_FIELDS
                }
                fixes_map[filepath].add(Replacement(**filtered_replacement))
    return fixes_map


def _apply_fixes(yaml_files: List[str], cwd: Path = None) -> None:
    """
    Parses clang-tidy YAML files and applies the suggested fixes to the source files.

    Args:
        yaml_files: A list of paths to YAML files containing the fixes.
        cwd: The current working directory to resolve relative paths against.
    """

    fixes_map = _parse_fixes_from_yaml(yaml_files)
    for filepath_str, replacements in fixes_map.items():
        filepath = Path(filepath_str)
        if cwd:
            filepath = cwd / filepath

        if not filepath.exists():
            print(f"Skipping ghost file: {filepath}", file=sys.stderr)
            continue

        logging.debug("Applying %d fixes to %s", len(replacements), filepath)

        with open(filepath, "rb") as f:
            code_bytes = f.read()

        # Sort replacements in reverse order of offset to
        # avoid corrupting byte offsets for subsequent replacements.
        # Note the we have a special case where multiple inserts can happen at the
        # same offset. For example when renaming a variable and introducing const,
        # usually the length == 0 (it's an insertion), so we want to do those after
        # the initial replacement.
        replacements = sorted(replacements, key=lambda x: (-x.Offset, -x.Length))

        for r in replacements:
            start = r.Offset
            end = start + r.Length
            # The replacement text from clang-tidy may contain C-style escape sequences
            # (e.g., '\\n', '\\t'). To correctly apply these as their literal byte
            # values, we first encode to bytes, then decode using 'unicode_escape' to
            # interpret the escapes, and finally re-encode to UTF-8 for writing to the file.
            replacement_bytes = (
                r.ReplacementText.encode("utf-8")
                .decode("unicode_escape")
                .encode("utf-8")
            )
            logging.debug(
                "Applying fix to %s: start=%d, end=%d, replacement=`%s`",
                filepath,
                start,
                end,
                r.ReplacementText,
            )
            code_bytes = code_bytes[:start] + replacement_bytes + code_bytes[end:]

        # Write the modified content back to the file.
        with open(filepath, "wb") as f:
            f.write(code_bytes)


def _handle_combine(args: argparse.Namespace) -> None:
    """
    Reads multiple files and merges them.
    """
    combined_entries: List[str] = []

    for input_path in args.input_files:
        try:
            with open(input_path, "r", encoding="utf-8") as f:
                data = f.read()
                combined_entries.append(data)

        except IOError as e:
            print(f"Error merging {input_path}: {e}", file=sys.stderr)
            sys.exit(1)

    with open(args.output_file, "w", encoding="utf-8") as f:
        f.write("\n".join(combined_entries))


def _deep_merge(source, destination):
    """
    Recursively merges 'source' dictionary into 'destination' dictionary.

    If both source and destination keys are dictionaries, they are merged recursively.
    If both source and destination keys are lists, theu will be combined.
    Otherwise, the value from 'source' overwrites the value in 'destination'.

    Args:
        source (dict): The dictionary to merge from (its values will override).
        destination (dict): The dictionary to merge into (modified in place).

    Returns:
        dict: The updated destination dictionary.
    """
    if not source:
        return destination

    for key, value in source.items():
        if (
            key in destination
            and isinstance(destination[key], dict)
            and isinstance(value, dict)
        ):
            destination[key] = _deep_merge(value, destination[key])
        elif (
            key in destination
            and isinstance(destination[key], list)
            and isinstance(value, list)
        ):
            destination[key].extend(value)
        else:
            destination[key] = value

    return destination


def _process_chunk(file_paths: List[str]) -> Dict[Any, Any]:
    """
    Worker function: Reads a subset of files and merges them into a local dictionary.
    This runs inside a separate process with its own memory space.
    """
    chunk_combined = {}
    for input_path in file_paths:
        with open(input_path, "r", encoding="utf-8") as f:
            data = yaml.load(f, Loader=Loader)
            if data:
                _deep_merge(data, chunk_combined)

    return chunk_combined


def _handle_combine_tidy(args: argparse.Namespace) -> None:
    """
    Parallel implementation of the merge logic.
    """
    input_files = []
    if args.input_files_file:
        with open(args.input_files_file, "r") as f:
            input_files = [line.strip() for line in f if line.strip()]
    if not input_files:
        # Create empty output file if no inputs
        with open(args.output_file, "w", encoding="utf-8") as f:
            f.write("")
        return

    # Use CPU count, but safeguard against overhead for tiny file counts
    cpu_count = os.cpu_count() or 4
    max_workers = min(cpu_count, len(input_files))

    # Some metrics that justify the multi threading
    # INFO: Elapsed time: 557.204s, Critical Path: 484.02s < multi c parse
    # INFO: Elapsed time: 616.495s, Critical Path: 579.76s < single thread c parse
    # INFO: Elapsed time: 1067.791s, Critical Path: 1025.37s < single thread python parser

    if max_workers > 1:
        chunk_size = math.ceil(len(input_files) / max_workers)
        chunks = [
            input_files[i : i + chunk_size]
            for i in range(0, len(input_files), chunk_size)
        ]
    else:
        chunks = [input_files]

    final_entries: Dict[Any, Any] = {}

    if max_workers > 1:
        # ProcessPoolExecutor bypasses the GIL by forking the process
        with ProcessPoolExecutor(max_workers=max_workers) as executor:
            for partial_result in executor.map(_process_chunk, chunks):
                _deep_merge(partial_result, final_entries)

    else:
        final_entries = _process_chunk(input_files)

    with open(args.output_file, "w", encoding="utf-8") as f:
        yaml.dump(final_entries, f, Dumper=Dumper)


def main() -> None:
    parser = _create_parser()

    args = parser.parse_args()
    _setup_logging(args.verbose)

    logging.debug("Starting clang-tidy utility in %s mode.", args.mode)
    logging.debug("Received args: %s", args)

    if args.mode == "generate":
        _handle_generate(args)
    elif args.mode == "fix":
        _apply_fixes(
            yaml_files=args.fixes_files,
            cwd=Path(args.working_dir, args.subdir),
        )
    elif args.mode == "combine-text":  # Renamed from combine
        _handle_combine(args)
    elif args.mode == "combine-tidy":
        _handle_combine_tidy(args)


if __name__ == "__main__":
    main()
